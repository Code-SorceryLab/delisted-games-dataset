#!/usr/bin/env python3

"""
Export title-overlap datasets between DoesItPlay and each outcome source.

The script reads the unified CSV generated by the aggregation pipeline and
creates three manual-review datasets:

    - DoesItPlay x Steam Tracker
    - DoesItPlay x Delisted Games
    - DoesItPlay x Dead Game List

Only outcome-source rows flagged `is_historically_unavailable` are used, so
"At Risk" games that are still running are excluded.

Matching is intentionally conservative: rows are joined only when
`normalized_title` is exactly equal. The exports preserve the original title
from both sources and source-specific/raw fields so that each match can be
manually validated.

The output includes blank `manual_match` and `manual_notes` columns to support
human review.

Expected input:
    ../Analysis/unified_games.csv

Outputs:
    ./
        overlap_doesitplay_steam_tracker.csv
        overlap_doesitplay_delisted_games.csv
        overlap_doesitplay_dead_game_list.csv
        overlap_export_summary.csv
"""

import logging
from pathlib import Path

import pandas as pd


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent

UNIFIED_CSV = (
    BASE_DIR.parent
    / "Analysis"
    / "unified_games.csv"
)

OUTPUT_DIR = BASE_DIR

TARGET_SOURCES = {
    "steam_tracker": "overlap_doesitplay_steam_tracker.csv",
    "delisted_games": "overlap_doesitplay_delisted_games.csv",
    "dead_game_list": "overlap_doesitplay_dead_game_list.csv",
}


logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
)

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def load_unified_csv(path: Path) -> pd.DataFrame:
    """
    Load and minimally validate the unified CSV.
    """
    logger.info("Loading unified dataset: %s", path)

    df = pd.read_csv(
        path,
        low_memory=False,
    )

    required_columns = {
        "source",
        "source_record_id",
        "game_name",
        "normalized_title",
    }

    missing = required_columns - set(df.columns)

    if missing:
        raise ValueError(
            "Unified CSV is missing required columns: "
            + ", ".join(sorted(missing))
        )

    # Empty normalized titles cannot be matched meaningfully.
    df["normalized_title"] = (
        df["normalized_title"]
        .fillna("")
        .astype(str)
        .str.strip()
    )

    return df


def existing_columns(
    df: pd.DataFrame,
    columns: list[str],
) -> list[str]:
    """
    Return only columns that actually exist in the dataframe.
    """
    return [
        column
        for column in columns
        if column in df.columns
    ]


def raw_columns_for_source(
    df: pd.DataFrame,
    source_name: str,
) -> list[str]:
    """
    Return raw source-specific columns for one source.
    """
    prefix_map = {
        "steam_tracker": [
            "raw__steamtracker__",
        ],
        "delisted_games": [
            "raw__delistedgames__",
        ],
        "dead_game_list": [
            "raw__deadgamelist__",
        ],
        "doesitplay": [
            "raw__doesitplay__",
        ],
    }

    prefixes = prefix_map[source_name]

    return [
        column
        for column in df.columns
        if any(
            column.startswith(prefix)
            for prefix in prefixes
        )
    ]


def prepare_source_side(
    df: pd.DataFrame,
    source_name: str,
) -> pd.DataFrame:
    """
    Select canonical and raw fields for one non-DoesItPlay source.

    All fields except normalized_title are renamed with a `source_` prefix
    so that the resulting review CSV is easy to inspect.
    """
    canonical_columns = [
        "normalized_title",
        "source_record_id",
        "game_name",
        "publisher",
        "developer",
        "platforms",
        "release_info",
        "event_info",
        "release_year",
        "event_year",
        "source_status",
        "is_explicitly_delisted",
        "is_historically_unavailable",
        "is_dead",
        "is_at_risk",
    ]

    columns = existing_columns(
        df,
        canonical_columns,
    )

    columns += raw_columns_for_source(
        df,
        source_name,
    )

    # Keep only games that are already unavailable (e.g. drop "At Risk"
    # Dead Game List entries), matching the historical event analysis.
    source_df = (
        df.loc[
            df["source"].eq(source_name)
            & df["normalized_title"].ne("")
            & df["is_historically_unavailable"].eq(True),
            columns,
        ]
        .copy()
    )

    rename_map = {
        column: f"source_{column}"
        for column in source_df.columns
        if column != "normalized_title"
    }

    source_df = source_df.rename(
        columns=rename_map
    )

    return source_df


def prepare_doesitplay_side(
    df: pd.DataFrame,
) -> pd.DataFrame:
    """
    Select canonical and raw DoesItPlay fields for manual comparison.
    """
    canonical_columns = [
        "normalized_title",
        "source_record_id",
        "game_name",
        "platforms",
        "source_status",
        "offline_play",
        "offline_play_bool",
        "download_required",
        "download_required_bool",
    ]

    columns = existing_columns(
        df,
        canonical_columns,
    )

    columns += raw_columns_for_source(
        df,
        "doesitplay",
    )

    doesitplay_df = (
        df.loc[
            df["source"].eq("doesitplay")
            & df["normalized_title"].ne(""),
            columns,
        ]
        .copy()
    )

    rename_map = {
        column: f"doesitplay_{column}"
        for column in doesitplay_df.columns
        if column != "normalized_title"
    }

    doesitplay_df = doesitplay_df.rename(
        columns=rename_map
    )

    return doesitplay_df


def export_overlap(
    unified: pd.DataFrame,
    source_name: str,
    doesitplay_df: pd.DataFrame,
    output_file: Path,
) -> dict:
    """
    Export all exact normalized-title matches between one source and DoesItPlay.

    Multiple rows are deliberately preserved. For example, a single game can
    have more than one DoesItPlay test because platform, version, region, or
    tested hardware differs.
    """
    source_df = prepare_source_side(
        unified,
        source_name,
    )

    overlap = source_df.merge(
        doesitplay_df,
        on="normalized_title",
        how="inner",
        validate="many_to_many",
    )

    overlap.insert(
        0,
        "matched_source",
        source_name,
    )

    overlap.insert(
        1,
        "match_type",
        "exact_normalized_title",
    )

    # Blank fields intentionally included for manual checking.
    overlap.insert(
        2,
        "manual_match",
        "",
    )

    overlap.insert(
        3,
        "manual_notes",
        "",
    )

    sort_columns = existing_columns(
        overlap,
        [
            "normalized_title",
            "source_source_record_id",
            "doesitplay_source_record_id",
        ],
    )

    if sort_columns:
        overlap = overlap.sort_values(
            sort_columns,
            kind="stable",
        )

    overlap = overlap.reset_index(
        drop=True,
    )

    output_file.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    overlap.to_csv(
        output_file,
        index=False,
    )

    unique_titles = (
        overlap["normalized_title"].nunique()
        if not overlap.empty
        else 0
    )

    logger.info(
        "%s x DoesItPlay: %d review rows, %d unique matched titles -> %s",
        source_name,
        len(overlap),
        unique_titles,
        output_file,
    )

    return {
        "source": source_name,
        "review_rows": int(len(overlap)),
        "unique_matched_titles": int(unique_titles),
        "output_file": output_file.name,
    }


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    unified = load_unified_csv(
        UNIFIED_CSV
    )

    doesitplay_df = prepare_doesitplay_side(
        unified
    )

    if doesitplay_df.empty:
        raise RuntimeError(
            "No DoesItPlay rows found in the unified dataset."
        )

    summary_rows = []

    for source_name, filename in TARGET_SOURCES.items():
        if not unified["source"].eq(source_name).any():
            raise RuntimeError(
                f"No rows found for source '{source_name}'."
            )

        summary = export_overlap(
            unified=unified,
            source_name=source_name,
            doesitplay_df=doesitplay_df,
            output_file=OUTPUT_DIR / filename,
        )

        summary_rows.append(
            summary
        )

    summary_df = pd.DataFrame(
        summary_rows
    )

    summary_path = (
        OUTPUT_DIR
        / "overlap_export_summary.csv"
    )

    summary_df.to_csv(
        summary_path,
        index=False,
    )

    print("\n=== DOESITPLAY OVERLAP EXPORT SUMMARY ===")
    print(
        summary_df.to_string(
            index=False
        )
    )

    print("\nFiles written:")
    for filename in TARGET_SOURCES.values():
        print(f"  - {OUTPUT_DIR / filename}")

    print(f"  - {summary_path}")


if __name__ == "__main__":
    main()
